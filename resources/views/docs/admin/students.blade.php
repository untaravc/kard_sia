<p>
    Halaman <strong>Data Mahasiswa</strong> digunakan oleh administrator untuk mengelola data
    mahasiswa (residen). Anda dapat menambah, mengubah, menghapus, serta mengakses informasi
    terkait setiap mahasiswa.
</p>

<h5>Mencari Mahasiswa</h5>
<ul>
    <li><strong>Keyword</strong> — mencari berdasarkan nama atau email.</li>
    <li><strong>Status</strong> — menyaring berdasarkan Active/Nonactive.</li>
    <li><strong>Year</strong> — menyaring berdasarkan tahun masuk.</li>
</ul>
<p>Klik <strong>Search</strong> untuk menerapkan filter atau <strong>Reset</strong> untuk mengosongkannya.</p>

<h5>Menambah Mahasiswa</h5>
<ol>
    <li>Klik tombol <strong>Add Student</strong> di kanan atas.</li>
    <li>
        Lengkapi data pada formulir: <strong>Name</strong>, <strong>Email</strong>,
        <strong>Password</strong>, <strong>Year</strong>, dan <strong>Status</strong>
        (Active/Nonactive).
    </li>
    <li>Klik <strong>Create Student</strong> untuk menyimpan.</li>
</ol>

<h5>Tindakan pada Setiap Mahasiswa</h5>
<p>Pada setiap baris, klik tombol <strong>Actions</strong> untuk menampilkan menu:</p>
<ul>
    <li><strong>Score</strong> — membuka halaman nilai mahasiswa tersebut.</li>
    <li><strong>Presences</strong> — membuka data presensi mahasiswa.</li>
    <li><strong>Print Logbook</strong> — mencetak logbook mahasiswa (terbuka pada tab baru).</li>
    <li><strong>Log As</strong> — masuk ke sistem sebagai mahasiswa tersebut (membuka dashboard mahasiswa pada tab baru).</li>
    <li><strong>Edit</strong> — memperbarui data mahasiswa, lalu klik <em>Update Student</em>.</li>
    <li><strong>Delete</strong> — menghapus mahasiswa (akan diminta konfirmasi).</li>
</ul>

<h5>Navigasi Halaman</h5>
<p>Gunakan tombol <strong>Prev</strong> dan <strong>Next</strong> di bawah daftar untuk berpindah halaman.</p>
