<p>
    Halaman <strong>Data Stase</strong> digunakan oleh administrator untuk mengelola daftar stase
    (rotasi). Anda dapat menambah, mengubah, menghapus stase, serta mengakses daftar tugas pada
    masing-masing stase.
</p>

<h5>Mencari Stase</h5>
<p>
    Gunakan kolom <strong>Keyword</strong> untuk mencari berdasarkan nama, lalu klik
    <strong>Search</strong>. Klik <strong>Reset</strong> untuk mengosongkan pencarian.
</p>

<h5>Menambah Stase</h5>
<ol>
    <li>Klik tombol <strong>Add Stase</strong> di kanan atas.</li>
    <li>
        Lengkapi formulir:
        <ul>
            <li><strong>Name</strong> — nama stase.</li>
            <li><strong>Alias</strong> — nama singkat/alias.</li>
            <li><strong>Color</strong> dan <strong>Font Color</strong> — warna penanda stase.</li>
            <li><strong>Description</strong> — keterangan (mis. penanda tahap).</li>
            <li><strong>Order</strong> — urutan tampil stase.</li>
            <li><strong>Lecture Name</strong> / <strong>Lecture Names</strong> — nama dosen pengampu.</li>
            <li><strong>Evaluation Link</strong> — tautan evaluasi.</li>
        </ul>
    </li>
    <li>Klik <strong>Create Stase</strong> untuk menyimpan.</li>
</ol>

<h5>Tindakan pada Setiap Stase</h5>
<p>Setiap baris menampilkan warna penanda, nama, alias, deskripsi, dan jumlah tugas. Tersedia tombol:</p>
<ul>
    <li><strong>Tasks</strong> — membuka halaman daftar tugas stase tersebut (lihat <em>Data Tugas Stase</em>).</li>
    <li><strong>Edit</strong> — memperbarui data stase, lalu klik <em>Update Stase</em>.</li>
    <li><strong>Delete</strong> — menghapus stase (akan diminta konfirmasi).</li>
</ul>

<h5>Navigasi Halaman</h5>
<p>Gunakan tombol <strong>Prev</strong> dan <strong>Next</strong> di bawah daftar untuk berpindah halaman.</p>
