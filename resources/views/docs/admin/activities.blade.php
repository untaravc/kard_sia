<p>
    Halaman <strong>Agenda</strong> digunakan oleh administrator untuk mengelola agenda/kegiatan.
    Anda dapat menambah, mengubah, dan menghapus agenda.
</p>

<h5>Mencari Agenda</h5>
<p>
    Gunakan kolom <strong>Keyword</strong> untuk mencari berdasarkan nama, judul, atau pembicara,
    lalu klik <strong>Search</strong>. Klik <strong>Reset</strong> untuk mengosongkan pencarian.
</p>

<h5>Menambah Agenda</h5>
<ol>
    <li>Klik tombol <strong>Add Activity</strong> di kanan atas untuk membuka halaman formulir.</li>
    <li>
        Lengkapi data agenda:
        <ul>
            <li><strong>Nama</strong> dan <strong>Pembicara</strong>.</li>
            <li><strong>Judul</strong> dan <strong>Stase</strong> terkait.</li>
            <li><strong>Mulai</strong> dan <strong>Selesai</strong> — tanggal dan waktu kegiatan.</li>
            <li>
                <strong>Tipe</strong> — sasaran peserta: <em>Umum</em> (residen dan/atau staff),
                <em>Staff</em>, <em>Residen</em>, atau <em>Residen Wajib</em>.
            </li>
            <li><strong>Tempat</strong>, <strong>Kategori</strong>, dan <strong>Status</strong> (Active/Draft/Nonactive).</li>
            <li><strong>Link</strong> dan <strong>Passcode</strong> — untuk kegiatan daring.</li>
        </ul>
    </li>
    <li>Klik <strong>Save Activity</strong> untuk menyimpan, atau <strong>Back</strong> untuk kembali tanpa menyimpan.</li>
</ol>

<h5>Tindakan pada Setiap Agenda</h5>
<p>Setiap baris menampilkan nama, status, judul, pembicara, serta waktu mulai dan selesai. Tersedia tombol:</p>
<ul>
    <li><strong>Edit</strong> — membuka kembali halaman formulir untuk memperbarui agenda.</li>
    <li><strong>Delete</strong> — menghapus agenda (akan diminta konfirmasi).</li>
</ul>

<h5>Navigasi Halaman</h5>
<p>Gunakan tombol <strong>Prev</strong> dan <strong>Next</strong> di bawah daftar untuk berpindah halaman.</p>
