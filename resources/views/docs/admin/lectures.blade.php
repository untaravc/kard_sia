<p>
    Halaman <strong>Data Dosen</strong> digunakan oleh administrator untuk mengelola data dosen
    (pengajar). Anda dapat menambah, mengubah, menghapus, serta masuk sebagai dosen tertentu.
</p>

<h5>Mencari Dosen</h5>
<ul>
    <li>
        Gunakan kolom <strong>Keyword</strong> untuk mencari berdasarkan nama atau email, lalu klik
        <strong>Search</strong>.
    </li>
    <li>Klik <strong>Reset</strong> untuk mengosongkan pencarian.</li>
</ul>

<h5>Menambah Dosen</h5>
<ol>
    <li>Klik tombol <strong>Add Lecture</strong> di kanan atas.</li>
    <li>
        Lengkapi data pada formulir: <strong>Number</strong>, <strong>Name</strong>,
        <strong>Email</strong>, <strong>Password</strong>, <strong>Alternate Name</strong>,
        <strong>Status</strong> (Active/Nonactive), dan opsi <strong>In House</strong>.
    </li>
    <li>Klik <strong>Create Lecture</strong> untuk menyimpan.</li>
</ol>

<h5>Tindakan pada Setiap Dosen</h5>
<p>Pada setiap baris, klik tombol <strong>Actions</strong> untuk menampilkan menu:</p>
<ul>
    <li><strong>Log As</strong> — masuk ke sistem sebagai dosen tersebut (membuka dashboard dosen pada tab baru).</li>
    <li><strong>Edit</strong> — memperbarui data dosen melalui formulir, lalu klik <em>Update Lecture</em>.</li>
    <li><strong>Delete</strong> — menghapus dosen (akan diminta konfirmasi).</li>
</ul>

<h5>Navigasi Halaman</h5>
<p>Gunakan tombol <strong>Prev</strong> dan <strong>Next</strong> di bawah daftar untuk berpindah halaman.</p>
