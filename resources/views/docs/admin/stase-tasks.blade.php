<p>
    Halaman <strong>Data Tugas Stase</strong> digunakan oleh administrator untuk mengelola daftar
    tugas pada sebuah stase. Halaman ini diakses dengan menekan tombol <strong>Tasks</strong> pada
    salah satu stase di halaman <em>Data Stase</em>.
</p>
<p>
    Di bagian atas ditampilkan informasi stase yang sedang dikelola (warna penanda, nama, alias,
    dan deskripsi).
</p>

<h5>Menambah Tugas Stase</h5>
<ol>
    <li>Klik tombol <strong>Add Stase Task</strong> di kanan atas.</li>
    <li>
        Lengkapi formulir:
        <ul>
            <li><strong>Name</strong> — nama tugas.</li>
            <li><strong>Status</strong> — <em>active</em> atau <em>non-active</em>.</li>
            <li><strong>Task ID</strong> — ID tugas yang dirujuk.</li>
            <li><strong>Lecture ID</strong> — ID dosen penilai.</li>
        </ul>
    </li>
    <li>Klik <strong>Create Stase Task</strong> untuk menyimpan.</li>
</ol>

<h5>Tindakan pada Setiap Tugas</h5>
<p>
    Setiap baris menampilkan nama tugas, status, serta tugas dan dosen terkait. Tersedia tombol:
</p>
<ul>
    <li><strong>Edit</strong> — memperbarui data tugas, lalu klik <em>Update Stase Task</em>.</li>
    <li><strong>Delete</strong> — menghapus tugas (akan diminta konfirmasi).</li>
</ul>

<h5>Navigasi Halaman</h5>
<p>Gunakan tombol <strong>Prev</strong> dan <strong>Next</strong> di bawah daftar untuk berpindah halaman.</p>
