<p>
    Halaman <strong>Surat</strong> digunakan oleh administrator untuk mengelola surat. Anda dapat
    menambah, mengubah, menggandakan, mengajukan tanda tangan, serta menghapus surat.
</p>

<h5>Mencari Surat</h5>
<ul>
    <li><strong>Keyword</strong> — mencari berdasarkan judul atau nomor surat.</li>
    <li><strong>Status</strong> — menyaring berdasarkan <em>Draft</em> atau <em>Published</em>.</li>
</ul>
<p>Klik <strong>Search</strong> untuk menerapkan filter atau <strong>Reset</strong> untuk mengosongkannya.</p>

<h5>Menambah / Mengubah Surat</h5>
<p>
    Klik tombol <strong>Add Letter</strong> (atau <strong>Edit</strong> pada surat yang ada) untuk
    membuka halaman formulir. Lengkapi data berikut:
</p>
<ul>
    <li><strong>Number</strong> — nomor surat (kosongkan untuk dibuat otomatis) dan <strong>Date</strong>.</li>
    <li><strong>Title</strong> dan <strong>Subtitle</strong>.</li>
    <li><strong>Status</strong> — Draft atau Published.</li>
    <li><strong>Intro</strong>, <strong>Body</strong>, dan <strong>Outro</strong> — isi surat menggunakan editor teks.</li>
    <li><strong>Attachment Label</strong> dan <strong>Attachment Content</strong> — lampiran surat.</li>
    <li><strong>Custom Invitation</strong> — teks undangan khusus (opsional).</li>
    <li>
        <strong>Undangan</strong> — klik <em>Tambah Undangan</em> untuk memilih user/dosen/residen
        yang diundang.
    </li>
    <li>
        <strong>Approval</strong> — klik <em>Pilih Approval</em> untuk menentukan satu approver
        (penanda tangan) surat.
    </li>
</ul>
<p>Klik <strong>Save Letter</strong> untuk menyimpan, atau <strong>Back</strong> untuk kembali tanpa menyimpan.</p>

<h5>Tindakan pada Setiap Surat</h5>
<p>Pada setiap baris, klik tombol <strong>Actions</strong> untuk menampilkan menu:</p>
<ul>
    <li><strong>Preview</strong> — melihat pratinjau surat pada tab baru (surat yang sudah <em>Published</em> ditampilkan versi publiknya).</li>
    <li><strong>Edit</strong> — membuka halaman formulir untuk memperbarui surat.</li>
    <li>
        <strong>Propose</strong> / <strong>Notify</strong> — untuk surat draft, <em>Propose</em>
        mengirim pengajuan tanda tangan via WhatsApp; untuk surat yang sudah Published,
        <em>Notify</em> mengirim notifikasi ke approver.
    </li>
    <li><strong>Clone</strong> — menggandakan surat. Isi <em>Title</em> dan <em>Date</em> baru, lalu klik <em>Clone</em>; surat hasil gandaan langsung dibuka untuk diedit.</li>
    <li><strong>Delete</strong> — menghapus surat (akan diminta konfirmasi).</li>
</ul>

<h5>Navigasi Halaman</h5>
<p>Gunakan tombol <strong>Prev</strong> dan <strong>Next</strong> di bawah daftar untuk berpindah halaman.</p>
