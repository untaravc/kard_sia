<p>
    Halaman <strong>Penilaian</strong> digunakan oleh mahasiswa (residen) untuk mengelola stase
    dan mengakses rincian penilaiannya. Halaman ini menampilkan dua kolom: <strong>Available
    Stase</strong> (stase yang tersedia untuk diambil) di sebelah kiri dan <strong>Taken
    Stase</strong> (stase yang telah diambil) di sebelah kanan.
</p>

<h5>Mengambil Stase (Take Stase)</h5>
<p>Untuk mengambil stase yang tersedia:</p>
<ol>
    <li>Pada kolom <strong>Available Stase</strong>, klik tombol <strong>Take Stase</strong> pada stase yang dituju.</li>
    <li>
        Pada jendela <strong>Take Stase</strong>, isi <strong>Start date</strong> (tanggal mulai)
        dan <strong>End date</strong> (tanggal selesai).
    </li>
    <li>Klik <strong>Save</strong> untuk menyimpan.</li>
</ol>
<p>
    Setelah berhasil, akan muncul notifikasi <em>“Stase saved.”</em> dan stase tersebut berpindah
    ke kolom <strong>Taken Stase</strong>.
</p>

<h5>Mengubah Jadwal Stase</h5>
<p>
    Pada kolom <strong>Taken Stase</strong>, setiap stase menampilkan periode tanggalnya. Untuk
    memperbarui jadwal:
</p>
<ol>
    <li>Klik tombol <strong>Edit</strong> pada stase terkait.</li>
    <li>Perbarui <strong>Start date</strong> dan/atau <strong>End date</strong> pada jendela <em>Edit Stase</em>.</li>
    <li>Klik <strong>Save</strong> untuk menyimpan perubahan (notifikasi <em>“Stase updated.”</em> akan muncul).</li>
</ol>

<h5>Melihat Rincian Penilaian</h5>
<p>
    Klik tombol <strong>Detail</strong> pada stase yang telah diambil untuk membuka halaman
    rincian penilaian stase tersebut, di mana Anda dapat melihat penilaian per tugas stase.
</p>
