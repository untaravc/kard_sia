<p>
    Halaman <strong>Student Logbook</strong> digunakan oleh mahasiswa (residen) untuk mengisi dan
    memantau logbook pada setiap stase. Halaman ini dapat diakses melalui menu logbook pada
    dashboard mahasiswa.
</p>

<h5>Memilih Stase</h5>
<p>
    Pada panel <strong>Log Book</strong> di sisi kiri ditampilkan daftar stase beserta periode
    tanggalnya. Anda dapat:
</p>
<ul>
    <li>Mencari stase melalui kolom <strong>Cari stase..</strong>.</li>
    <li>
        Menekan tombol <strong>Logbook</strong> pada stase yang dituju untuk membuka data logbook
        dan capaian keterampilan stase tersebut.
    </li>
</ul>

<h5>Capaian Keterampilan (Skill Achievements)</h5>
<p>
    Setelah stase dipilih, panel <strong>Skill Achievements</strong> menampilkan daftar
    keterampilan beserta capaian Anda dalam format <em>jumlah capaian / target</em>. Capaian akan
    bertambah seiring keterampilan dicentang saat pengisian logbook.
</p>

<h5>Menambah Entri Logbook</h5>
<p>Untuk menambahkan data logbook pada sebuah jenis logbook:</p>
<ol>
    <li>Klik tombol <strong>Add New</strong> pada jenis logbook yang dituju.</li>
    <li>
        Pada jendela <strong>Tambah Log Book</strong>, lengkapi data umum:
        <ul>
            <li><strong>Tanggal</strong> — tanggal kegiatan (default hari ini).</li>
            <li><strong>Tipe</strong> — terisi otomatis sesuai jenis logbook.</li>
            <li>
                <strong>Supervisor</strong> — pilih dosen pembimbing, atau
                <em>Departmen Lain</em> bila supervisor bukan dari Departemen.
            </li>
            <li><strong>Kategori</strong> — pilih kategori logbook.</li>
        </ul>
    </li>
    <li>
        Isi kolom <strong>Detail</strong> sesuai field yang tersedia. Anda dapat menambah beberapa
        data sekaligus dengan tombol <strong>Add Row</strong>, atau menghapus baris dengan
        <strong>Remove</strong>.
    </li>
    <li>
        Bila tersedia, centang <strong>Ketrampilan</strong> yang dicapai pada setiap baris untuk
        menambah capaian keterampilan.
    </li>
    <li>Klik <strong>Simpan</strong> untuk menyimpan seluruh data.</li>
</ol>

<h5>Mengubah dan Menghapus Entri</h5>
<p>
    Pada tabel logbook, gunakan tombol <strong>Actions</strong> di setiap baris untuk:
</p>
<ul>
    <li><strong>Edit</strong> — membuka jendela <em>Edit Log Book</em> untuk memperbarui data dan keterampilan, lalu klik <strong>Update</strong>.</li>
    <li><strong>Delete</strong> — menghapus entri (akan diminta konfirmasi terlebih dahulu).</li>
</ul>

<h5>Mencetak Logbook</h5>
<p>
    Tombol <strong>Print</strong> pada panel logbook stase digunakan untuk mencetak logbook stase
    terpilih. Cetakan akan terbuka pada tab baru.
</p>
