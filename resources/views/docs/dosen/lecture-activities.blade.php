<p>
    Halaman <strong>Presensi Agenda Ilmiah</strong> menampilkan daftar agenda ilmiah dan
    digunakan oleh dosen untuk melakukan <em>check-in</em> (presensi) kehadiran pada agenda
    tersebut. Halaman ini umumnya tampil pada dashboard dosen.
</p>

<h5>Melihat Agenda</h5>
<p>
    Secara default ditampilkan <strong>Agenda Hari Ini</strong>. Setiap agenda menampilkan nama
    kegiatan, pembicara dan judul materi, serta waktu mulai dan selesai.
</p>
<ul>
    <li>
        Gunakan tombol panah <strong>&lsaquo;</strong> dan <strong>&rsaquo;</strong> di samping
        tanggal untuk berpindah ke hari sebelumnya atau berikutnya.
    </li>
    <li>
        Klik <strong>Semua agenda</strong> untuk membuka daftar seluruh agenda.
    </li>
    <li>
        Bila tidak ada agenda pada tanggal terpilih, akan muncul keterangan
        <em>“Tidak ada agenda.”</em>
    </li>
</ul>

<h5>Melakukan Check-In</h5>
<p>Untuk mencatat kehadiran pada sebuah agenda:</p>
<ol>
    <li>Klik tombol <strong>Check In</strong> pada agenda yang dituju.</li>
    <li>
        Pada jendela <strong>Detail Agenda</strong> akan tampil informasi kegiatan dan waktunya.
        Klik tombol <strong>Check In</strong> untuk mengonfirmasi.
    </li>
    <li>
        Setelah berhasil, agenda akan menampilkan keterangan
        <em>“Anda check-in pada …”</em> beserta waktu presensi, dan tombol Check In tidak lagi
        ditampilkan untuk agenda tersebut.
    </li>
</ol>

<h5>Check-In Terlambat</h5>
<p>
    Jika check-in dilakukan setelah waktu selesai agenda, sistem menampilkan peringatan bahwa
    <em>check-in terlambat akan mengirim notifikasi ke pembuat agenda</em>. Presensi tetap dapat
    dilakukan, namun pembuat agenda akan menerima pemberitahuan atas keterlambatan tersebut.
</p>
