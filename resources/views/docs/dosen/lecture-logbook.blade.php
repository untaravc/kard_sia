<p>
    Halaman <strong>Pratinjau Logbook Residen</strong> digunakan oleh dosen untuk meninjau dan
    menyetujui logbook yang diisi oleh residen (mahasiswa). Halaman ini dapat diakses melalui menu
    <em>Logbooks</em> pada dashboard dosen.
</p>

<h5>Menyaring Logbook</h5>
<p>Pada bagian atas tersedia beberapa filter untuk mempermudah pencarian:</p>
<ul>
    <li><strong>Keyword</strong> — mencari berdasarkan isi field logbook.</li>
    <li><strong>Stase</strong> — menyaring logbook berdasarkan stase tertentu.</li>
    <li><strong>Student</strong> — menyaring logbook milik residen tertentu.</li>
    <li>
        <strong>Status</strong> — menyaring berdasarkan status:
        <em>Pending</em>, <em>Approved</em>, atau <em>Rejected</em>.
        Secara default ditampilkan logbook berstatus <em>Pending</em>.
    </li>
</ul>
<p>
    Klik tombol <strong>Search</strong> untuk menerapkan filter, atau <strong>Reset</strong>
    untuk mengembalikan filter ke kondisi awal.
</p>

<h5>Melihat Detail Logbook</h5>
<p>
    Setiap baris logbook menampilkan jenis logbook, status, stase, nama residen, kategori, dan
    tanggal. Klik tombol <strong>View</strong> pada sebuah baris untuk membuka detail lengkapnya,
    termasuk seluruh isian field (Field 1–6) yang dikirim oleh residen.
</p>

<h5>Menyetujui Logbook</h5>
<p>
    Pada panel <strong>Approval All Filtered Logbook</strong> ditampilkan jumlah logbook yang
    sesuai dengan filter aktif. Untuk menyetujui seluruh logbook tersebut sekaligus:
</p>
<ol>
    <li>Tentukan filter terlebih dahulu (misalnya stase, residen, dan status <em>Pending</em>).</li>
    <li>Klik tombol <strong>Approve</strong>.</li>
    <li>Pada jendela konfirmasi, klik <strong>Approve</strong> kembali untuk memproses.</li>
</ol>
<p>
    Setelah berhasil, sistem menampilkan jumlah logbook yang disetujui dan daftar akan diperbarui
    secara otomatis. Pastikan filter sudah benar sebelum menekan Approve, karena tindakan ini
    menyetujui <em>seluruh</em> logbook yang sedang tersaring, bukan hanya yang tampil pada halaman
    aktif.
</p>

<h5>Navigasi Halaman</h5>
<p>
    Gunakan tombol <strong>Prev</strong> dan <strong>Next</strong> di bagian bawah daftar untuk
    berpindah antar halaman bila jumlah logbook melebihi satu halaman.
</p>
