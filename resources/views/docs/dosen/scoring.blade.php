<p>
    Halaman <strong>Penilaian</strong> digunakan oleh dosen untuk memberikan nilai atas tugas
    stase residen yang membutuhkan penilaian. Halaman ini tampil pada dashboard dosen.
</p>

<h5>Ringkasan Penilaian</h5>
<p>Di bagian atas terdapat tiga kartu ringkasan:</p>
<ul>
    <li><strong>Tunda</strong> — jumlah tugas yang belum dinilai.</li>
    <li><strong>Selesai</strong> — jumlah penilaian yang sudah dilakukan pada bulan ini.</li>
    <li><strong>Riwayat</strong> — total seluruh riwayat penilaian.</li>
</ul>

<h5>Daftar Penilaian</h5>
<p>Pada panel <strong>Penilaian</strong> ditampilkan daftar tugas yang perlu dinilai. Anda dapat:</p>
<ul>
    <li>
        Menggunakan kolom <strong>Filter name…</strong> untuk mencari tugas berdasarkan nama
        residen.
    </li>
    <li>
        Membuka tautan <strong>Riwayat penilaian</strong> untuk melihat seluruh penilaian yang
        pernah dilakukan.
    </li>
    <li>
        Membuka lampiran/berkas tugas yang dikirim residen dengan menekan tombol berkas pada
        item terkait.
    </li>
</ul>

<h5>Memberikan Nilai</h5>
<p>Untuk memberi nilai pada sebuah tugas:</p>
<ol>
    <li>Klik tombol <strong>Nilai Langsung</strong> (atau <em>Nilai</em>) pada item yang dituju.</li>
    <li>
        Pada jendela <strong>Nilai Langsung</strong> akan tampil nama residen dan tugas stase
        terkait. Isi kolom <strong>Point Average</strong> dengan nilai yang sesuai.
    </li>
    <li>Klik <strong>Submit</strong> untuk menyimpan nilai.</li>
</ol>
<p>
    Setelah berhasil disimpan, daftar penilaian dan kartu ringkasan akan diperbarui secara
    otomatis. Untuk jenis tugas tertentu juga tersedia opsi penilaian khusus seperti
    <em>Nilai Thesis</em> dan <em>Nilai Proposal</em> beserta opsi pembaruannya.
</p>

<h5>Navigasi Halaman</h5>
<p>
    Gunakan tombol <strong>Prev</strong> dan <strong>Next</strong> di bawah daftar untuk berpindah
    halaman bila jumlah tugas melebihi satu halaman.
</p>
