<p>
    Halaman <strong>Profil</strong> menampilkan data dosen dan digunakan untuk memperbarui
    informasi pribadi. Halaman ini dapat diakses melalui menu profil pada dashboard dosen.
</p>

<h5>Informasi Profil</h5>
<p>
    Pada kartu profil ditampilkan foto, nama, email, nomor telepon, nama alternatif, dan alamat
    (bila tersedia). Tersedia pula pintasan ke <strong>Release Notes</strong>,
    <strong>Tutorial</strong>, dan <strong>PPDS Report</strong>.
</p>

<h5>Memperbarui Profil</h5>
<p>Untuk memperbarui data profil:</p>
<ol>
    <li>Klik tombol <strong>Perbarui Profil</strong>.</li>
    <li>
        Pada jendela yang muncul, perbarui data yang diperlukan:
        <ul>
            <li><strong>Foto</strong> — unggah foto profil baru (maksimal ±4&nbsp;MB).</li>
            <li><strong>Email</strong></li>
            <li><strong>Nama</strong></li>
            <li><strong>Password Baru</strong> dan <strong>Konfirmasi Password Baru</strong> — isi hanya bila ingin mengganti kata sandi.</li>
            <li><strong>No Telepon</strong></li>
            <li><strong>Alamat</strong></li>
        </ul>
    </li>
    <li>Klik <strong>Simpan</strong> untuk menyimpan perubahan.</li>
</ol>
<p>
    Setelah berhasil, akan muncul notifikasi <em>“Profile updated successfully.”</em> dan data
    profil dimuat ulang secara otomatis. Kolom kata sandi akan dikosongkan kembali setelah
    penyimpanan. Kosongkan kolom Password Baru jika Anda tidak ingin mengubah kata sandi.
</p>
